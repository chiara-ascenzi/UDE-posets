"""
move_types2.py -- classes of connected posets generated by the "basic" moves
(one-point moves, flip-flops, the cut of Corollary 3.8) versus all
admissible cuts.

Backs the column "both kinds and Cor. 3.8" of Table 2 of the paper
(values 3, 6, 27, 184, 2203 for n = 4..8) and again the column "all cuts"
(3, 6, 23, 117, 1284).  The other columns come from move_types.py.

A cut counts as basic if
  * it is of singleton type (every M(a) is a singleton: Ladkani's flip-flop), or
  * |A| = 1 or |B| = 1 (one-point moves), or
  * P has height <= 1 and A = Min(P) (the cut of Corollary 3.8).

Output: one JSON line per n with
  classes_click_sing_height1 : classes generated by the basic cuts,
  classes_all                : classes generated by all admissible cuts,
  cuts_not_click_sing_height1_noniso : non-basic cuts with P^- not isomorphic to P.

usage: python3 move_types2.py NMAX
"""

import json
import sys

from admissible_cuts import ideals, check_cut, negative_poset, popcount, to_mask
from canonical import all_posets, canonical_strings, poset_to_d6
from census import UnionFind


def main(nmax):
    for n in range(2, nmax + 1):
        Ps = all_posets(n)
        N = len(Ps)
        canon = canonical_strings([poset_to_d6(P) for P in Ps])
        idx = {c: i for i, c in enumerate(canon)}
        rows = []
        for i, P in enumerate(Ps):
            full = P.full()
            h1 = P.height() <= 1
            mins = to_mask(P.minimal())
            for A in ideals(P):
                if A in (0, full):
                    continue
                good, _, M = check_cut(P, A)
                if not good or all(v == 0 for v in M.values()):
                    continue
                single = all(popcount(v) == 1 for v in M.values())
                click = popcount(A) == 1 or popcount(full & ~A) == 1
                height1 = h1 and A == mins
                rows.append((i, single, click, height1,
                             poset_to_d6(negative_poset(P, A, M))))
        tg = canonical_strings([r[4] for r in rows])
        u_basic = UnionFind(N)
        u_all = UnionFind(N)
        non_basic = 0
        for (i, single, click, h1, _), c in zip(rows, tg):
            j = idx[c]
            u_all.union(i, j)
            if single or click or h1:
                u_basic.union(i, j)
            elif j != i:
                non_basic += 1
        conn = [i for i in range(N) if Ps[i].is_connected()]
        print(json.dumps({
            "n": n,
            "classes_click_sing_height1": len(set(u_basic.find(i) for i in conn)),
            "classes_all": len(set(u_all.find(i) for i in conn)),
            "cuts_not_click_sing_height1_noniso": non_basic}))
        sys.stdout.flush()


if __name__ == "__main__":
    main(int(sys.argv[1]))
