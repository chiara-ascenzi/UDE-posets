"""
census.py -- admissible cuts of all posets with n points.

For every poset P (up to isomorphism) with n points:
  * enumerate all ideals A (Definition 3.1 (a)) and test (b), (c);
  * for each admissible cut record |M(a)|, singleton type, and the
    isomorphism class of P^- (Corollary 3.3);
  * count the Aut(P)-orbits of cuts through canonical forms of the poset
    with A marked by loops.

Then build the move graph on isomorphism classes (edge P -- P^- for every
admissible cut with P^- not isomorphic to P).  Its connected components are
exactly the ~_L-classes, i.e. the classes of the equivalence relation
generated by Ladkani's construction (Theorem 2.2) on n-element posets
(every application of the construction is an edge, by Theorem 3.2 applied
to the positive poset).  Components are
compared with the derived invariants of invariants.py.

usage: python3 census.py NMAX [NMIN]
"""

import json
import sys
import time
from collections import Counter, defaultdict

from admissible_cuts import (bit, members, popcount, ideals, check_cut,
                             negative_poset)
from canonical import (all_posets, canonical_strings, encode_digraph6,
                       poset_to_d6)
from invariants import coxeter_polynomial, betti_numbers


def marked_d6(P, A):
    rows = [(P.up[x] & ~bit(x)) | (bit(x) if (A >> x) & 1 else 0)
            for x in range(P.n)]
    return encode_digraph6(P.n, rows)


def undirected_hasse_d6(P):
    rows = [0] * P.n
    for x, y in P.covers():
        rows[x] |= bit(y)
        rows[y] |= bit(x)
    return encode_digraph6(P.n, rows)


class UnionFind:
    def __init__(self, n):
        self.p = list(range(n))

    def find(self, x):
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[max(ra, rb)] = min(ra, rb)


def census(n, verbose=True):
    t0 = time.time()
    Ps = all_posets(n)
    N = len(Ps)
    canon = canonical_strings([poset_to_d6(P) for P in Ps])
    idx = {c: i for i, c in enumerate(canon)}
    assert len(idx) == N
    op_idx = [idx[c] for c in canonical_strings([poset_to_d6(P.op()) for P in Ps])]

    per = []            # per-poset statistics
    cut_owner = []      # (i, singleton?, maxM, |A|) for every effective cut
    out_d6, mark_d6 = [], []
    full_stats = Counter()
    for i, P in enumerate(Ps):
        full = P.full()
        n_id = n_adm = n_inert = 0
        fails = Counter()
        for A in ideals(P):
            if A == 0 or A == full:
                continue
            n_id += 1
            good, why, M = check_cut(P, A)
            if not good:
                fails[why] += 1
                continue
            n_adm += 1
            if all(Ma == 0 for Ma in M.values()):
                n_inert += 1
                continue
            Pm = negative_poset(P, A, M)
            sizes = [popcount(Ma) for Ma in M.values()]
            cut_owner.append((i, all(s == 1 for s in sizes), max(sizes), popcount(A)))
            out_d6.append(poset_to_d6(Pm))
            mark_d6.append(marked_d6(P, A))
        per.append({"n_ideals": n_id, "n_adm": n_adm, "n_inert": n_inert,
                    "fail_b": fails["(b)"], "fail_c": fails["(c)"]})
    t1 = time.time()
    outs = canonical_strings(out_d6)
    marks = canonical_strings(mark_d6)
    del out_d6, mark_d6
    t2 = time.time()

    # ---- move graph -------------------------------------------------------
    uf = UnionFind(N)
    out_sets = [set() for _ in range(N)]
    orbits = [set() for _ in range(N)]
    n_eff = [0] * N
    n_isotriv = [0] * N
    n_nonsingleton_eff = [0] * N
    for k, (i, single, maxM, sizeA) in enumerate(cut_owner):
        j = idx[outs[k]]
        n_eff[i] += 1
        orbits[i].add(marks[k])
        if j == i:
            n_isotriv[i] += 1
        else:
            out_sets[i].add(j)
            uf.union(i, j)
            if not single:
                n_nonsingleton_eff[i] += 1
    comp = [uf.find(i) for i in range(N)]

    # ---- invariants -----------------------------------------------------------
    cox = [coxeter_polynomial(P) for P in Ps]
    betti = [betti_numbers(P) for P in Ps]
    t3 = time.time()

    # ---- summaries --------------------------------------------------------
    connected = [P.is_connected() for P in Ps]
    comps = defaultdict(list)
    for i in range(N):
        comps[comp[i]].append(i)
    inv_classes = defaultdict(list)
    for i in range(N):
        inv_classes[(cox[i], betti[i])].append(i)

    split = []
    for key, members_ in inv_classes.items():
        cs = sorted(set(comp[i] for i in members_))
        if len(cs) > 1:
            split.append({"coxeter": list(key[0]), "betti": list(key[1]),
                          "connected": connected[members_[0]],
                          "components": [[i for i in members_ if comp[i] == c]
                                         for c in cs]})

    # directed asymmetry on isomorphism classes
    asym = sum(1 for i in range(N) for j in out_sets[i] if i not in out_sets[j])
    n_dir_edges = sum(len(s) for s in out_sets)
    # op-closure
    op_fail = [i for i in range(N) if comp[i] != comp[op_idx[i]]]
    self_dual = sum(1 for i in range(N) if op_idx[i] == i)

    # trees
    is_tree = [P.hasse_is_tree() for P in Ps]
    tree_ids = [i for i in range(N) if is_tree[i]]
    tree_canon = dict(zip(tree_ids, canonical_strings(
        [undirected_hasse_d6(Ps[i]) for i in tree_ids])))
    trees_in_comp = defaultdict(set)
    for i in tree_ids:
        trees_in_comp[comp[i]].add(tree_canon[i])
    tree_conflicts = [c for c, s in trees_in_comp.items() if len(s) > 1]
    tree_comp_members = [i for i in range(N) if comp[i] in trees_in_comp]
    nontree_in_tree_comps = [i for i in tree_comp_members if not is_tree[i]]

    # tree -> tree cuts (question (ii) of the notes)
    tree_cut_total = tree_cut_to_tree = 0
    for k, (i, single, maxM, sizeA) in enumerate(cut_owner):
        if is_tree[i]:
            j = idx[outs[k]]
            tree_cut_total += 1
            if is_tree[j]:
                tree_cut_to_tree += 1

    # rigid posets = isolated vertices of the move graph
    isolated = [i for i in range(N) if len(comps[comp[i]]) == 1]
    isolated_conn = [i for i in isolated if connected[i]]

    conn_ids = [i for i in range(N) if connected[i]]
    conn_comps = set(comp[i] for i in conn_ids)
    conn_inv = set((cox[i], betti[i]) for i in conn_ids)

    summary = {
        "n": n,
        "posets": N,
        "connected_posets": len(conn_ids),
        "self_dual_posets": self_dual,
        "nontrivial_ideals": sum(p["n_ideals"] for p in per),
        "admissible_cuts": sum(p["n_adm"] for p in per),
        "inert_cuts": sum(p["n_inert"] for p in per),
        "effective_cuts": sum(n_eff),
        "effective_cuts_nonsingleton_type": sum(1 for c in cut_owner if not c[1]),
        "effective_aut_orbits": sum(len(o) for o in orbits),
        "iso_trivial_cuts": sum(n_isotriv),
        "distinct_outputs_total": sum(len(s) for s in out_sets),
        "failures_b": sum(p["fail_b"] for p in per),
        "failures_c": sum(p["fail_c"] for p in per),
        "posets_with_noniso_output": sum(1 for s in out_sets if s),
        "move_components": len(comps),
        "move_components_connected": len(conn_comps),
        "invariant_classes": len(inv_classes),
        "invariant_classes_connected": len(conn_inv),
        "split_invariant_classes": len(split),
        "split_invariant_classes_connected": sum(1 for s in split if s["connected"]),
        "largest_component": max(len(v) for v in comps.values()),
        "isolated_posets": len(isolated),
        "isolated_connected_posets": len(isolated_conn),
        "directed_edges": n_dir_edges,
        "directed_edges_without_reverse": asym,
        "posets_not_in_component_of_opposite": len(op_fail),
        "tree_posets": len(tree_ids),
        "tree_components": len(trees_in_comp),
        "tree_components_with_two_trees": len(tree_conflicts),
        "nontree_posets_in_tree_components": len(nontree_in_tree_comps),
        "cuts_of_tree_posets": tree_cut_total,
        "cuts_of_tree_posets_giving_trees": tree_cut_to_tree,
        "posets_needing_nonsingleton_for_some_edge": sum(1 for v in n_nonsingleton_eff if v),
        "time_cuts_s": round(t1 - t0, 1),
        "time_canon_s": round(t2 - t1, 1),
        "time_invariants_s": round(t3 - t2, 1),
    }
    detail = {
        "covers": [Ps[i].covers() for i in range(N)],
        "canon": canon,
        "comp": comp,
        "op_idx": op_idx,
        "cox": [list(c) for c in cox],
        "betti": [list(b) for b in betti],
        "connected": connected,
        "is_tree": is_tree,
        "out_sets": [sorted(s) for s in out_sets],
        "n_eff": n_eff,
        "n_isotriv": n_isotriv,
        "n_orbits": [len(o) for o in orbits],
        "per": per,
        "split": split,
        "isolated": isolated,
        "op_fail": op_fail,
        "tree_conflicts": [sorted(trees_in_comp[c]) for c in tree_conflicts],
    }
    if verbose:
        print(json.dumps(summary))
        sys.stdout.flush()
    return summary, detail


if __name__ == "__main__":
    nmax = int(sys.argv[1])
    nmin = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    for n in range(nmin, nmax + 1):
        s, d = census(n)
        with open("census_n%d.json" % n, "w") as f:
            json.dump({"summary": s, "detail": d}, f)
