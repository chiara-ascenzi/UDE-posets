"""
closure.py -- equivalence relations generated by known constructions, on
CONNECTED posets with n points, compared with derived invariants.

  L    : Ladkani, Theorem 1.1 (admissible cuts; computed in census.py)
  LP   : L + products (Ladkani 0705.0946, Lemma 2.9: X1~Y1, X2~Y2 => X1xX2 ~ Y1xY2)
  LPS  : LP + lexicographic sums along bipartite graphs
         (Ladkani math/0610685, Theorem 4.14: sum_S X ~ sum_{S^op} X;
          this one is stated for derived equivalence over a field)

A poset is connected iff b_0 = 1, and the number of connected components
is a derived invariant, so it is enough to study connected posets.

usage: python3 closure.py NMAX      (needs census_n*.json from census.py)
"""

import json
import sys
from collections import defaultdict
from itertools import product as iproduct

from admissible_cuts import Poset, bit, members
from canonical import canonical_strings, poset_to_d6
from census import UnionFind


def load(n):
    with open("census_n%d.json" % n) as f:
        d = json.load(f)["detail"]
    Ps = [Poset.from_relations(n, [tuple(c) for c in cov]) for cov in d["covers"]]
    return Ps, d


def product_poset(X, Y):
    m = Y.n
    up = [0] * (X.n * m)
    for x in range(X.n):
        for y in range(m):
            mask = 0
            for x2 in members(X.up[x]):
                for y2 in members(Y.up[y]):
                    mask |= bit(x2 * m + y2)
            up[x * m + y] = mask
    return Poset.from_up(X.n * m, up)


def lex_sum(S, Xs):
    """Lexicographic sum of the posets Xs[s] along the poset S."""
    off = []
    tot = 0
    for X in Xs:
        off.append(tot)
        tot += X.n
    block = [((1 << X.n) - 1) << off[s] for s, X in enumerate(Xs)]
    up = [0] * tot
    for s, X in enumerate(Xs):
        above = 0
        for t in members(S.up[s] & ~bit(s)):
            above |= block[t]
        for x in range(X.n):
            up[off[s] + x] = (X.up[x] << off[s]) | above
    return Poset.from_up(tot, up)


def compositions(n, k):
    if k == 1:
        yield (n,)
        return
    for first in range(1, n - k + 2):
        for rest in compositions(n - first, k - 1):
            yield (first,) + rest


def main(nmax):
    data = {}            # n -> (Ps, detail)
    for n in range(1, nmax + 1):
        data[n] = load(n)
    idx = {n: {c: i for i, c in enumerate(data[n][1]["canon"])} for n in data}
    # class labels per size, for the two closures, filled in increasing n
    label_LP = {}
    label_LPS = {}
    report = {}
    for n in range(1, nmax + 1):
        Ps, d = data[n]
        N = len(Ps)
        conn = d["connected"]
        ufL = UnionFind(N)
        for i in range(N):
            ufL.union(i, d["comp"][i])
        ufLP = UnionFind(N)
        ufLPS = UnionFind(N)
        for i in range(N):
            ufLP.union(i, d["comp"][i])
            ufLPS.union(i, d["comp"][i])

        # ---- products X x Y with |X| = k <= |Y| = m, k*m = n, both >= 2 -----
        prod_pairs_LP, prod_pairs_LPS = [], []
        for k in range(2, n):
            if n % k or k > n // k:
                continue
            m = n // k
            PX, dX = data[k]
            PY, dY = data[m]
            Xs = [i for i in range(len(PX)) if dX["connected"][i]]
            Ys = [j for j in range(len(PY)) if dY["connected"][j]]
            triples = []   # (poset, key) to canonicalise in batch
            for i in Xs:
                for j in Ys:
                    triples.append(product_poset(PX[i], PY[j]))
            cans = canonical_strings([poset_to_d6(P) for P in triples])
            pos = {}
            t = 0
            for i in Xs:
                for j in Ys:
                    pos[(i, j)] = idx[n][cans[t]]
                    t += 1
            for lab, pairs in ((label_LP, prod_pairs_LP), (label_LPS, prod_pairs_LPS)):
                repX = {}
                for i in Xs:
                    repX.setdefault(lab[k][i], i)
                repY = {}
                for j in Ys:
                    repY.setdefault(lab[m][j], j)
                for (i, j), p in pos.items():
                    pairs.append((p, pos[(repX[lab[k][i]], j)]))
                    pairs.append((p, pos[(i, repY[lab[m][j]])]))
        for a, b in prod_pairs_LP:
            ufLP.union(a, b)
        for a, b in prod_pairs_LPS:
            ufLPS.union(a, b)

        # ---- lexicographic sums along connected bipartite S (>= 2 vertices) --
        lex_P, lex_Q = [], []
        n_lex = 0
        for k in range(2, n + 1):
            PS, dS = data[k]
            Ss = [PS[i] for i in range(len(PS))
                  if dS["connected"][i] and PS[i].height() <= 1]
            for S in Ss:
                Sop = S.op()
                for comp_ in compositions(n, k):
                    if all(c == 1 for c in comp_):
                        continue        # S ~ S^op: already Corollary 3.8
                    lists = [data[c][0] for c in comp_]
                    for choice in iproduct(*lists):
                        lex_P.append(lex_sum(S, list(choice)))
                        lex_Q.append(lex_sum(Sop, list(choice)))
                        n_lex += 1
        cP = canonical_strings([poset_to_d6(P) for P in lex_P])
        cQ = canonical_strings([poset_to_d6(P) for P in lex_Q])
        n_lex_new = 0
        for a, b in zip(cP, cQ):
            ia, ib = idx[n][a], idx[n][b]
            if ufLPS.find(ia) != ufLPS.find(ib):
                n_lex_new += 1
            ufLPS.union(ia, ib)
        del lex_P, lex_Q

        label_LP[n] = [ufLP.find(i) for i in range(N)]
        label_LPS[n] = [ufLPS.find(i) for i in range(N)]

        # ---- compare with invariants on connected posets ----------------------
        inv = defaultdict(list)
        for i in range(N):
            if conn[i]:
                inv[(tuple(d["cox"][i]), tuple(d["betti"][i]))].append(i)
        conn_ids = [i for i in range(N) if conn[i]]
        rep = {
            "n": n,
            "connected_posets": len(conn_ids),
            "classes_L": len(set(ufL.find(i) for i in conn_ids)),
            "classes_LP": len(set(label_LP[n][i] for i in conn_ids)),
            "classes_LPS": len(set(label_LPS[n][i] for i in conn_ids)),
            "invariant_classes": len(inv),
            "split_after_L": sum(1 for v in inv.values()
                                 if len(set(ufL.find(i) for i in v)) > 1),
            "split_after_LP": sum(1 for v in inv.values()
                                  if len(set(label_LP[n][i] for i in v)) > 1),
            "split_after_LPS": sum(1 for v in inv.values()
                                   if len(set(label_LPS[n][i] for i in v)) > 1),
            "lex_pairs_generated": n_lex,
            "lex_pairs_joining_new_classes": n_lex_new,
            "op_not_in_class_L": sum(1 for i in conn_ids
                                     if ufL.find(i) != ufL.find(d["op_idx"][i])),
            "op_not_in_class_LPS": sum(1 for i in conn_ids
                                       if label_LPS[n][i] != label_LPS[n][d["op_idx"][i]]),
        }
        report[n] = rep
        print(json.dumps(rep))
        sys.stdout.flush()
        with open("closure_n%d.json" % n, "w") as f:
            json.dump({"report": rep, "label_L": [ufL.find(i) for i in range(N)],
                       "label_LP": label_LP[n], "label_LPS": label_LPS[n]}, f)
    return report


if __name__ == "__main__":
    main(int(sys.argv[1]))
