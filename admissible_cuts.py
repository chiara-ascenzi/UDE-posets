"""
admissible_cuts.py -- reference implementation of the admissible-cut criterion.

Implements, for a finite poset P:
  * Definition 3.1 (admissible cut) and the test of Theorem 3.2,
  * the associated negative poset P^- (Corollary 3.3),
  * the reconstruction of P from P^- and the partition (Proposition 3.4),
  * Ladkani's positive/negative posets for arbitrary data (Section 2.2),
    used only for independent verification.

Conventions
-----------
A poset on the ground set {0, ..., n-1} is stored through two lists of
bitmasks:
    up[x]   = { y : x <= y }   (x included)
    down[x] = { y : y <= x }   (x included)
Subsets of the ground set are bitmasks as well.

Pure Python 3, no dependencies (runs unchanged inside SageMath).
"""

from itertools import permutations


# ----------------------------------------------------------------------------
# bitmask helpers
# ----------------------------------------------------------------------------

def bit(i):
    return 1 << i


def members(mask):
    """Elements of a bitmask, in increasing order."""
    while mask:
        low = mask & -mask
        yield low.bit_length() - 1
        mask ^= low


def popcount(mask):
    return bin(mask).count("1")


def to_set(mask):
    return set(members(mask))


def to_mask(elements):
    m = 0
    for e in elements:
        m |= bit(e)
    return m


# ----------------------------------------------------------------------------
# posets
# ----------------------------------------------------------------------------

class Poset:
    """Finite poset on {0,...,n-1}, stored by up-sets and down-sets."""

    __slots__ = ("n", "up", "down")

    def __init__(self, n, up, down):
        self.n = n
        self.up = list(up)
        self.down = list(down)

    # -- constructors --------------------------------------------------------
    @classmethod
    def from_relations(cls, n, pairs):
        """Poset generated by the relations x <= y for (x, y) in pairs
        (reflexive-transitive closure).  Raises ValueError on a cycle."""
        up = [bit(x) for x in range(n)]
        for x, y in pairs:
            up[x] |= bit(y)
        # Warshall's algorithm on bit rows
        for k in range(n):
            bk = bit(k)
            uk = up[k]
            for i in range(n):
                if up[i] & bk:
                    up[i] |= uk
        return cls.from_up(n, up)

    @classmethod
    def from_up(cls, n, up):
        down = [0] * n
        for x in range(n):
            for y in members(up[x]):
                down[y] |= bit(x)
        P = cls(n, up, down)
        if not P.is_partial_order():
            raise ValueError("relation is not a partial order")
        return P

    @classmethod
    def from_down(cls, n, down):
        up = [0] * n
        for x in range(n):
            for y in members(down[x]):
                up[y] |= bit(x)
        P = cls(n, up, down)
        if not P.is_partial_order():
            raise ValueError("relation is not a partial order")
        return P

    # -- basic queries ---------------------------------------------------------
    def leq(self, x, y):
        return (self.up[x] >> y) & 1 == 1

    def lt(self, x, y):
        return x != y and self.leq(x, y)

    def is_partial_order(self):
        n = self.n
        for x in range(n):
            if not (self.up[x] >> x) & 1:                 # reflexive
                return False
            for y in members(self.up[x]):
                if y != x and (self.up[y] >> x) & 1:      # antisymmetric
                    return False
                if self.up[y] & ~self.up[x]:              # transitive
                    return False
        return True

    def covers(self):
        """Covering pairs (x, y): x < y with nothing strictly in between."""
        res = []
        for x in range(self.n):
            above = self.up[x] & ~bit(x)
            for y in members(above):
                between = above & self.down[y] & ~bit(y)
                if between == 0:
                    res.append((x, y))
        return res

    def minimal(self):
        return [x for x in range(self.n) if self.down[x] == bit(x)]

    def maximal(self):
        return [x for x in range(self.n) if self.up[x] == bit(x)]

    def op(self):
        return Poset(self.n, self.down, self.up)

    def full(self):
        return (1 << self.n) - 1

    def key(self):
        """Labelled identity of the poset (equality of relations)."""
        return tuple(self.up)

    def __eq__(self, other):
        return isinstance(other, Poset) and self.n == other.n and self.up == other.up

    def __hash__(self):
        return hash(self.key())

    def __repr__(self):
        return "Poset(n=%d, covers=%s)" % (self.n, self.covers())

    def height(self):
        """Length r of a longest chain x0 < ... < xr."""
        order = self.linear_extension()
        best = [0] * self.n
        for x in order:
            for y in members(self.down[x] & ~bit(x)):
                best[x] = max(best[x], best[y] + 1)
        return max(best) if self.n else -1

    def linear_extension(self):
        return sorted(range(self.n), key=lambda x: popcount(self.down[x]))

    def is_connected(self):
        if self.n == 0:
            return True
        seen = 1
        frontier = 1
        while frontier:
            new = 0
            for x in members(frontier):
                new |= self.up[x] | self.down[x]
            frontier = new & ~seen
            seen |= new
        return seen == self.full()

    def hasse_is_tree(self):
        """True iff the undirected Hasse diagram is a tree."""
        return self.is_connected() and len(self.covers()) == self.n - 1


# ----------------------------------------------------------------------------
# ideals
# ----------------------------------------------------------------------------

def ideals(P):
    """All order ideals (down-closed subsets) of P, as bitmasks.
    Each ideal is produced exactly once."""
    order = P.linear_extension()
    strict_down = [P.down[x] & ~bit(x) for x in range(P.n)]
    out = []

    def rec(i, cur):
        if i == len(order):
            out.append(cur)
            return
        x = order[i]
        rec(i + 1, cur)
        if strict_down[x] & ~cur == 0:
            rec(i + 1, cur | bit(x))

    rec(0, 0)
    return out


def is_ideal(P, S):
    return all(P.down[x] & ~S == 0 for x in members(S))


def is_filter(P, S):
    return all(P.up[x] & ~S == 0 for x in members(S))


# ----------------------------------------------------------------------------
# Definition 3.1 / Theorem 3.2
# ----------------------------------------------------------------------------

def M_sets(P, A, B):
    """M(a) = Min_B(U_B(a)) for every a in A (dict a -> bitmask)."""
    M = {}
    for a in members(A):
        U = P.up[a] & B
        mins = 0
        for u in members(U):
            if P.down[u] & U == bit(u):
                mins |= bit(u)
        M[a] = mins
    return M


def check_cut(P, A):
    """Test whether P = A |_| B (B the complement of A) is an admissible cut.

    Returns (ok, failed_condition, M) where failed_condition is one of
    None, '(a)', '(b)', '(c)'.  M is None if (a) fails."""
    B = P.full() & ~A
    # (a) A ideal (equivalently B filter)
    for a in members(A):
        if P.down[a] & B:
            return False, "(a)", None
    M = M_sets(P, A, B)
    # (b) separation
    for a, Ma in M.items():
        ms = list(members(Ma))
        for i in range(len(ms)):
            for j in range(i + 1, len(ms)):
                m1, m2 = ms[i], ms[j]
                if P.up[m1] & P.up[m2] & B or P.down[m1] & P.down[m2] & B:
                    return False, "(b)", M
    # (c) compatibility
    for a in members(A):
        for a2 in members(P.up[a] & A & ~bit(a)):
            for m in members(M[a]):
                if P.up[m] & M[a2] == 0:
                    return False, "(c)", M
    return True, None, M


def negative_poset(P, A, M):
    """P^- for an admissible cut (Corollary 3.3):
    orders on A and B unchanged, b <=^- a iff b <= m for some m in M(a)."""
    B = P.full() & ~A
    down = [0] * P.n
    for x in range(P.n):
        if (A >> x) & 1:
            below = 0
            for m in members(M[x]):
                below |= P.down[m] & B
            down[x] = (P.down[x] & A) | below
        else:
            down[x] = P.down[x] & B
    return Poset.from_down(P.n, down)   # raises if not a partial order


def reconstruct_from_negative(Pm, A):
    """Proposition 3.4: recover P from P^- and the partition A |_| B.
    M(a) = Max_B(L^-_B(a)),  a <=_P b iff m <=_B b for some m in M(a)."""
    B = Pm.full() & ~A
    up = [0] * Pm.n
    Mrec = {}
    for a in members(A):
        L = Pm.down[a] & B
        maxs = 0
        for l in members(L):
            if Pm.up[l] & L == bit(l):
                maxs |= bit(l)
        Mrec[a] = maxs
    for x in range(Pm.n):
        if (A >> x) & 1:
            above = 0
            for m in members(Mrec[x]):
                above |= Pm.up[m] & B
            up[x] = (Pm.up[x] & A) | above
        else:
            up[x] = Pm.up[x] & B
    return Poset.from_up(Pm.n, up), Mrec


class Cut:
    """Certificate of an admissible cut: the partition, the sets M(a)
    and the resulting negative poset."""

    __slots__ = ("A", "B", "M", "Pminus")

    def __init__(self, A, B, M, Pminus):
        self.A, self.B, self.M, self.Pminus = A, B, M, Pminus

    def is_inert(self):
        """No mixed relations at all (then P^- = P)."""
        return all(Ma == 0 for Ma in self.M.values())

    def is_singleton_type(self):
        return all(popcount(Ma) == 1 for Ma in self.M.values())

    def max_M(self):
        return max((popcount(Ma) for Ma in self.M.values()), default=0)

    def as_dict(self):
        return {
            "A": sorted(to_set(self.A)),
            "B": sorted(to_set(self.B)),
            "M": {a: sorted(to_set(Ma)) for a, Ma in self.M.items()},
            "Pminus_covers": self.Pminus.covers(),
        }


def admissible_cuts(P, include_trivial=False):
    """All admissible cuts of P, as Cut certificates.

    Only ideals A are enumerated (condition (a)).  Unless include_trivial,
    the cuts with A empty or B empty are skipped (they give P^- = P)."""
    full = P.full()
    res = []
    for A in ideals(P):
        if not include_trivial and (A == 0 or A == full):
            continue
        ok, _, M = check_cut(P, A)
        if ok:
            res.append(Cut(A, full & ~A, M, negative_poset(P, A, M)))
    return res


# ----------------------------------------------------------------------------
# Ladkani's construction for arbitrary data (verification only)
# ----------------------------------------------------------------------------

def _has_monotone_bijection(P, Y1, Y2):
    """Is there a bijection phi: Y1 -> Y2 with y <= phi(y)?"""
    l1, l2 = list(members(Y1)), list(members(Y2))
    if len(l1) != len(l2):
        return False
    for perm in permutations(l2):
        if all(P.leq(y, z) for y, z in zip(l1, perm)):
            return True
    return False


def ladkani_hypotheses(P, A, B, family):
    """Hypotheses (i), (ii) of Section 2.2 for X = A, Y = B with the orders
    induced from P, and family = dict a -> bitmask of B."""
    for a in members(A):
        ys = list(members(family[a]))
        for i in range(len(ys)):
            for j in range(i + 1, len(ys)):
                y1, y2 = ys[i], ys[j]
                if P.up[y1] & P.up[y2] & B or P.down[y1] & P.down[y2] & B:
                    return False
    for a in members(A):
        for a2 in members(P.up[a] & A & ~bit(a)):
            if not _has_monotone_bijection(P, family[a], family[a2]):
                return False
    return True


def ladkani_positive_up(P, A, B, family):
    """Up-sets of (A |_| B)^+ built from the orders induced by P on A and B."""
    up = [0] * P.n
    for x in range(P.n):
        if (A >> x) & 1:
            above = 0
            for y in members(family[x]):
                above |= P.up[y] & B
            up[x] = (P.up[x] & A) | above
        else:
            up[x] = P.up[x] & B
    return up
