"""
move_types.py -- which kinds of admissible cuts are needed?

Compares, on connected posets with n points, the equivalence relations
generated by
  CLICK : cuts with A = {s} (source-clicks, Prop. 4.1) or B = {t}
          (the dual one-point moves),
  SING  : cuts of singleton type (Ladkani's flip-flops, Proposition 2.3
          and Corollary 3.10),
  ALL   : all admissible cuts (Theorem 2.2, via Theorem 3.2).
Columns "one-point cuts", "singleton type", "both kinds" and "all cuts"
of Table 2 of the paper.

usage: python3 move_types.py NMAX
"""

import json
import sys

from admissible_cuts import ideals, check_cut, negative_poset, popcount, members
from canonical import all_posets, canonical_strings, poset_to_d6
from census import UnionFind


def main(nmax):
    for n in range(2, nmax + 1):
        Ps = all_posets(n)
        N = len(Ps)
        canon = canonical_strings([poset_to_d6(P) for P in Ps])
        idx = {c: i for i, c in enumerate(canon)}
        owners, kinds, outs = [], [], []
        for i, P in enumerate(Ps):
            full = P.full()
            for A in ideals(P):
                if A == 0 or A == full:
                    continue
                good, _, M = check_cut(P, A)
                if not good or all(v == 0 for v in M.values()):
                    continue
                single = all(popcount(v) == 1 for v in M.values() if v) and \
                    all(popcount(v) == 1 for v in M.values())
                click = popcount(A) == 1 or popcount(full & ~A) == 1
                owners.append(i)
                kinds.append((click, single))
                outs.append(poset_to_d6(negative_poset(P, A, M)))
        tgt = [idx[c] for c in canonical_strings(outs)]
        uf = {k: UnionFind(N) for k in ("CLICK", "SING", "CLICK_OR_SING", "ALL")}
        for i, j, (click, single) in zip(owners, tgt, kinds):
            uf["ALL"].union(i, j)
            if click:
                uf["CLICK"].union(i, j)
            if single:
                uf["SING"].union(i, j)
            if click or single:
                uf["CLICK_OR_SING"].union(i, j)
        conn = [i for i in range(N) if Ps[i].is_connected()]
        rep = {"n": n, "connected": len(conn)}
        for k, u in uf.items():
            rep["classes_" + k] = len(set(u.find(i) for i in conn))
        print(json.dumps(rep))
        sys.stdout.flush()


if __name__ == "__main__":
    main(int(sys.argv[1]))
