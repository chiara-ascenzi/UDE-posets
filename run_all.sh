#!/bin/sh
# run_all.sh -- recomputes every computational statement of the paper
#   C. Ascenzi, "Derived equivalences between diagram categories of finite posets".
#
#   sh run_all.sh
#
# Outputs go to results/ and data/.  The large intermediate files
# census_n*.json, closure_n*.json, residual_n*.json stay in the current
# directory: later scripts read them.
set -e
mkdir -p results data

echo "[1/10] tests of the implementation; Theorem 3.2 by brute force for n <= 6 (Section 5.1)"
python3 tests.py 7 6 > results/tests.txt

echo "[2/10] census, ~_L-classes, invariants for n <= 9 (Section 5.2, Table 1, Theorem 5.1)"
python3 census.py   9 > results/census_n1-9.jsonl
python3 closure.py  9 > results/closure_n1-9.jsonl
python3 residual.py 9 > results/residual_n1-9.jsonl
python3 make_summary.py 9 > results/summary_table_n1-9.md

echo "[3/10] independent recomputation for n <= 6 (proof of Theorem 5.1)"
python3 independent_check.py 6 > results/independent_check_n6.txt

echo "[4/10] similarity of Coxeter matrices modulo p <= 47 for alpha and beta (Section 5.3)"
python3 modp.py 6 > results/modp_n6.jsonl

echo "[5/10] restricted kinds of cuts (Section 5.4, Table 2)"
python3 move_types.py  8 > results/move_types_n2-8.jsonl
python3 move_types2.py 8 > results/move_types2_n2-8.jsonl
python3 essential_cuts.py 5 > results/essential_cuts_n5.txt

echo "[6/10] lexicographic sums not generated by admissible cuts, n = 8 (Section 5.5)"
python3 lex_new.py > results/lex_new_n8.txt

echo "[7/10] Lemma 3.5, Section 5.3, Appendix A.2, Example 4.7"
python3 extra_checks.py > results/extra_checks.txt

echo "[8/10] Remark after Proposition 3.12, Sections 5.1, 5.2, 5.5, Example 5.2"
python3 extra_checks2.py 9 > results/extra_checks2.txt

echo "[9/10] the ~_L-classes in machine-readable form (Appendix A.3)"
python3 export_classes.py 9 > results/export_classes.txt

echo "[10/10] the drawings and the table of Appendix A"
python3 gen_appendix.py > results/appendix_classes.tex

echo "done; see results/ and data/"
